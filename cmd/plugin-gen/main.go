// Command plugin-gen 在构建前发现插件包，生成显式导入与注册代码。
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const outputPath = "internal/plugin/builtin/registry_gen.go"

// packageInfo 是 go list 的构建上下文结果，仅解析当前目标选中的源码。
type packageInfo struct {
	Dir        string
	ImportPath string
	GoFiles    []string
	CgoFiles   []string
	Error      *struct{ Err string }
}

// main 读取生成器参数，生成或检查插件注册文件；失败时输出错误并退出。
func main() {
	root := flag.String("root", ".", "Go module root")
	check := flag.Bool("check", false, "check generated file without writing")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "plugin-gen accepts only -root and -check")
		os.Exit(1)
	}
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// run 先生成完整的注册代码，再替换旧文件；生成失败时保留旧文件。
// 检查模式只报告生成文件是否过期，不修改文件。
func run(root string, check bool) error {
	root, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	module, err := goOutput(root, "list", "-m", "-f", "{{.Path}}")
	if err != nil {
		return err
	}
	modulePath := strings.TrimSpace(string(module))
	if modulePath == "" || strings.ContainsAny(modulePath, "\r\n") {
		return errors.New("plugin-gen requires one Go module")
	}
	packages, err := discover(root)
	if err != nil {
		return err
	}
	generated, err := render(modulePath, packages)
	if err != nil {
		return err
	}
	destination := filepath.Join(root, outputPath)
	current, err := os.ReadFile(destination)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if bytes.Equal(current, generated) {
		return nil
	}
	if check {
		return errors.New("plugin registry is stale; run make generate")
	}
	if err := os.MkdirAll(filepath.Dir(destination), 0755); err != nil {
		return err
	}
	file, err := os.CreateTemp(filepath.Dir(destination), ".registry-*.go.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(generated); err != nil {
		file.Close()
		return err
	}
	if err := file.Chmod(0644); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), destination)
}

// discover 扫描插件目录并检查每个插件的构造函数，按包路径排序后返回。
// 除保留目录外，每个直接子目录都按插件处理；辅助包应放在更深层或 internal 目录中。
func discover(root string) ([]packageInfo, error) {
	entries, err := os.ReadDir(filepath.Join(root, "internal/plugin"))
	if err != nil {
		return nil, err
	}
	args := []string{"list", "-e", "-json"}
	for _, entry := range entries {
		name := entry.Name()
		if name == "builtin" || name == "internal" || name == "testdata" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
			continue
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return nil, fmt.Errorf("plugin entry %q must not be a symlink", name)
		}
		if entry.IsDir() {
			args = append(args, "./internal/plugin/"+name)
		}
	}
	if len(args) == 3 {
		return nil, nil
	}
	output, err := goOutput(root, args...)
	if err != nil {
		return nil, err
	}
	decoder := json.NewDecoder(bytes.NewReader(output))
	var packages []packageInfo
	for {
		var pkg packageInfo
		err := decoder.Decode(&pkg)
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, fmt.Errorf("decode go list: %w", err)
		}
		if pkg.Error != nil {
			return nil, fmt.Errorf("discover plugin %s: %s", pkg.ImportPath, pkg.Error.Err)
		}
		if err := validateConstructor(pkg); err != nil {
			return nil, err
		}
		packages = append(packages, pkg)
	}
	sort.Slice(packages, func(i, j int) bool { return packages[i].ImportPath < packages[j].ImportPath })
	return packages, nil
}

// validateConstructor 检查参与本次构建的源码是否声明了唯一的无参数 New 函数，且只返回一个结果。
// 返回类型是否实现 Provider 接口，由后续编译检查。
func validateConstructor(pkg packageInfo) error {
	files := append(append([]string(nil), pkg.GoFiles...), pkg.CgoFiles...)
	found := false
	for _, name := range files {
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(pkg.Dir, name), nil, 0)
		if err != nil {
			return fmt.Errorf("parse plugin %s: %w", pkg.ImportPath, err)
		}
		for _, declaration := range file.Decls {
			fn, ok := declaration.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || fn.Name.Name != "New" {
				continue
			}
			if found || fn.Type.Params.NumFields() != 0 || fn.Type.TypeParams.NumFields() != 0 || fn.Type.Results.NumFields() != 1 {
				return fmt.Errorf("plugin %s must declare exactly one func New() T returning a plugin.Provider", pkg.ImportPath)
			}
			found = true
		}
	}
	if !found {
		return fmt.Errorf("plugin %s is missing func New() T", pkg.ImportPath)
	}
	return nil
}

// render 生成插件导入和注册代码，用不同别名避免包名冲突；没有插件时也能生成可编译的代码。
func render(modulePath string, packages []packageInfo) ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by plugin-gen; DO NOT EDIT.")
	fmt.Fprintln(&out, "// 本文件由构建流程生成，显式装配全部发现的编译式插件。")
	fmt.Fprintln(&out, "package builtin")
	fmt.Fprintln(&out, "import (")
	fmt.Fprintf(&out, "%q\n", modulePath+"/internal/plugin")
	for i, pkg := range packages {
		fmt.Fprintf(&out, "provider%d %q\n", i, pkg.ImportPath)
	}
	fmt.Fprintln(&out, ")")
	fmt.Fprintln(&out, "// NewRegistry 创建本次构建包含的插件集合，并检查空实例及重复 ID。")
	fmt.Fprintln(&out, "func NewRegistry() (*plugin.Registry,error) {")
	fmt.Fprintln(&out, "return plugin.NewRegistry(")
	for i := range packages {
		fmt.Fprintf(&out, "provider%d.New(),\n", i)
	}
	fmt.Fprintln(&out, ")\n}")
	return format.Source(out.Bytes())
}

// goOutput 在指定目录运行本机 go 命令并读取输出，禁止自动下载其他版本的工具链。
func goOutput(root string, args ...string) ([]byte, error) {
	cmd := exec.Command("go", args...)
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOTOOLCHAIN=local")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	output, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go %s: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
	}
	return output, nil
}
